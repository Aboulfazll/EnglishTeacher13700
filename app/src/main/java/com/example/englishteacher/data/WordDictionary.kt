    fun lookup(word: String): String? {
        val clean = word
            .lowercase()
            .trim()
            .trim(',', '.', '!', '?', ';', ':', '"', '\'', '(', ')', '[', ']', '—', '-')
        return dictionary[clean]
    }

    fun contains(word: String): Boolean = lookup(word) != null
